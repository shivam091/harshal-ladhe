import "./shared/playground.css";
import "./shared/segmented-control.css";
import "./styles.css";

const $ = (id) => document.getElementById(id);
const carousel = $("carousel");
const slides = [...carousel.querySelectorAll(".slide")];

const supported = CSS.supports("scroll-marker-group", "after");
// Browsers without scrollsnapchange would leave the snapped slide stale, so the readout leaves that line out there.
const tracksSnap = "onscrollsnapchange" in window;
let current = slides[0];

/*
  The dots, arrows and active state need no JavaScript: styles.css generates them all. This script only applies the
  two controls and reports what the browser is doing.
*/
function update() {
  const group = document.querySelector("input[name='group']:checked").value;
  const style = document.querySelector("input[name='style']:checked").value;

  carousel.classList.toggle("group-before", group === "before");
  carousel.classList.toggle("markers-numbers", style === "numbers");

  const lines = [
    `support: ${supported ? "dots and arrows generated by CSS" : "not supported, plain scroll-snap row"}`,
    `scroll-marker-group: ${group}`
  ];
  if (tracksSnap) lines.push(`snapped to: ${current.dataset.label} (${slides.indexOf(current) + 1} of ${slides.length})`);
  $("readout").textContent = lines.join("\n");
}

// scrollsnapchange fires once a scroll settles on a new snap target, so the readout never needs to measure positions.
carousel.addEventListener("scrollsnapchange", (event) => {
  current = event.snapTargetInline;
  update();
});

document.querySelectorAll("input[type='radio']").forEach((input) => input.addEventListener("change", update));

update();
